#!/usr/bin/env python3
"""
gen_message_names.py — generate message-type name map for the Trezor Wireshark dissector.

Supports both:
  - messages.proto      enum MessageType_...
  - messages-thp.proto  enum ThpMessageType_...

Usage:
  python tools/gen_message_names.py /path/to/messages.proto
  python tools/gen_message_names.py /path/to/messages.proto /path/to/messages-thp.proto --inplace
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


BEGIN_MARK = "-- >>> BEGIN GENERATED MESSAGE NAMES (gen_message_names.py) >>>"
END_MARK = "-- <<< END GENERATED MESSAGE NAMES <<<"

ENTRY_RE = re.compile(
    r"\b(?P<prefix>MessageType|ThpMessageType)_(?P<name>[A-Za-z0-9_]+)\s*=\s*(?P<num>\d+)\s*(?:\[.*?\])?\s*;",
    re.DOTALL,
)


def parse_entries(paths: list[Path]) -> dict[int, str]:
    entries: dict[int, str] = {}

    for path in paths:
        text = path.read_text(encoding="utf-8")

        for match in ENTRY_RE.finditer(text):
            num = int(match.group("num"))
            name = match.group("name")

            # Prefer explicit THP names only if there is no normal MessageType
            # entry with the same number.
            if num not in entries:
                entries[num] = name

    if not entries:
        raise SystemExit("No MessageType entries parsed — are these the right proto files?")

    return entries


def render(entries: dict[int, str], source_paths: list[Path]) -> str:
    out: list[str] = []

    out.append(BEGIN_MARK)
    out.append("--")
    out.append("-- Generated by tools/gen_message_names.py.")
    out.append("-- Sources:")
    for path in source_paths:
        out.append(f"--   {path}")
    out.append("--")
    out.append("-- The message-type numbers are shared by Codec v1 and THP decrypted")
    out.append("-- application messages. Unknown values fall back to MessageType_<n>.")
    out.append("local v1_message_names = {")

    for num in sorted(entries):
        out.append(f'    [{num}] = "{entries[num]}",')

    out.append("}")
    out.append("")
    out.append("local function v1_message_name(msg_type)")
    out.append('    return v1_message_names[msg_type] or string.format("MessageType_%d", msg_type)')
    out.append("end")
    out.append(END_MARK)

    return "\n".join(out) + "\n"


def replace_generated_block(constants_path: Path, generated: str) -> None:
    text = constants_path.read_text(encoding="utf-8")

    start = text.find(BEGIN_MARK)
    end = text.find(END_MARK)

    if start == -1 or end == -1:
        raise SystemExit(f"Could not find generated block markers in {constants_path}")

    end += len(END_MARK)
    new_text = text[:start] + generated.rstrip() + text[end:]

    constants_path.write_text(new_text, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("proto", nargs="+", type=Path)
    parser.add_argument("--inplace", action="store_true")
    parser.add_argument(
        "--constants",
        type=Path,
        default=Path("src/02_constants.lua"),
        help="Path to src/02_constants.lua when using --inplace",
    )

    args = parser.parse_args()

    entries = parse_entries(args.proto)
    generated = render(entries, args.proto)

    if args.inplace:
        replace_generated_block(args.constants, generated)
        print(f"Updated {args.constants} ({len(entries)} entries)")
    else:
        print(generated, end="")


if __name__ == "__main__":
    main()
